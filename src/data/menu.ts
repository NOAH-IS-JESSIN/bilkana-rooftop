import type { MediaKey } from "./media";

export type CategoryId =
  | "breakfast"
  | "appetizers"
  | "salads"
  | "burgers"
  | "sandwiches"
  | "mains"
  | "italian"
  | "desserts"
  | "hot"
  | "cold";

export type Tag = "spicy" | "signature" | "seasonal" | "for-two";

export type Group = { id: string; label: string; labelAr: string };

export type Category = {
  id: CategoryId; // also the URL hash: /#italian
  label: string; // rail + index
  labelAr: string;
  intro: string;
  introAr: string;
  /** day = marble canvas; night = slate canvas (after the day-to-night bridge) */
  theme: "day" | "night";
  /**
   * Layout rhythm (see SITE_ARCHITECTURE.md):
   *  lead   — large editorial image + sets, then list
   *  split  — image and list side by side (tablet+), stacked on phones
   *  dense  — text-first, two columns from tablet
   *  ledger — text-first, big type, one column (few, higher-priced items)
   */
  layout: "lead" | "split" | "dense" | "ledger";
  visual: MediaKey;
  groups?: Group[];
};

export type MenuItem = {
  id: string;
  category: CategoryId;
  group?: string;
  name: string;
  nameAr: string;
  description?: string;
  descriptionAr?: string;
  /** JD, English menu. */
  price: number;
  /** Internal: the Arabic PDF's price when it differs. Never rendered. */
  arPdfPrice?: number | "missing";
  tags?: Tag[];
  vegetarian?: boolean;
  /** Photo of THIS item from Bilkana's own media. No photo → text row. */
  image?: MediaKey;
  /** Position in "Bilkana Selection" (1 = first). */
  featured?: number;
  keywords?: string;
  src: string;
};

